// Builds workflow.json from src/nodes/*.js + lib/*.js.
// Each Code node gets its entry file plus only the lib modules it needs,
// inlined, because the n8n task runner can't require() local files.
// Run: npm run build   (never edit the code inside workflow.json by hand)

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LIB = path.join(ROOT, 'lib');
const NODES = path.join(ROOT, 'src', 'nodes');

function libDeps(name, seen) {
  seen = seen || new Set();
  if (seen.has(name)) return seen;
  seen.add(name);
  const src = fs.readFileSync(path.join(LIB, name + '.js'), 'utf8');
  for (const m of src.matchAll(/require\('\.\/([\w-]+)(?:\.js)?'\)/g)) libDeps(m[1], seen);
  return seen;
}

function bundle(entryFile) {
  const entry = fs.readFileSync(path.join(NODES, entryFile), 'utf8');
  const mods = new Set();
  for (const m of entry.matchAll(/lib\('([\w-]+)'\)/g)) libDeps(m[1], mods);
  const defs = [...mods]
    .sort()
    .map((n) => '  ' + JSON.stringify(n) + ': function (module, exports, require) {\n' + fs.readFileSync(path.join(LIB, n + '.js'), 'utf8') + '\n  }')
    .join(',\n');
  return (
    '// GENERATED by scripts/build-workflow.js from src/nodes/' + entryFile + ' and lib/{' + [...mods].sort().join(',') + '}.js\n' +
    '// Edit those files and run "npm run build" instead of editing here.\n' +
    'const __defs = {\n' + defs + '\n};\n' +
    'const __cache = {};\n' +
    'function lib(name) {\n' +
    '  if (!__cache[name]) { const m = { exports: {} }; __cache[name] = m; __defs[name](m, m.exports, (n) => n.startsWith("./") ? lib(n.slice(2).replace(/\\.js$/, "")) : require(n)); }\n' +
    '  return __cache[name].exports;\n' +
    '}\n\n' +
    entry
  );
}

// ---------------------------------------------------------------- nodes
let x = 0;
const nodes = [];
const connections = {};
function node(name, type, typeVersion, parameters, pos, extra) {
  nodes.push(Object.assign({ id: 'n' + String(++x).padStart(2, '0') + '-' + type.split('.').pop().toLowerCase(), name, type, typeVersion, position: pos, parameters }, extra || {}));
  return name;
}
function code(name, file, pos, mode) {
  const p = { jsCode: bundle(file) };
  if (mode) p.mode = mode;
  return node(name, 'n8n-nodes-base.code', 2, p, pos);
}
function link(from, to, outIndex, inIndex) {
  connections[from] = connections[from] || { main: [] };
  const arr = connections[from].main;
  while (arr.length <= (outIndex || 0)) arr.push([]);
  arr[outIndex || 0].push({ node: to, type: 'main', index: inIndex || 0 });
}
function ifNode(name, leftExpr, operator, pos, rightValue) {
  return node(name, 'n8n-nodes-base.if', 2.2, {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
      conditions: [{ id: name + '-c', leftValue: leftExpr, rightValue: rightValue === undefined ? '' : rightValue, operator }],
      combinator: 'and',
    },
    looseTypeValidation: true,
    options: {},
  }, pos);
}
const TRUE = { type: 'boolean', operation: 'true', singleValue: true };
const NOT_EMPTY = { type: 'string', operation: 'notEmpty', singleValue: true };
function ending(name, htmlExpr, pos) {
  return node(name, 'n8n-nodes-base.form', 2.5, { operation: 'completion', respondWith: 'showText', responseText: htmlExpr, options: {} }, pos, { webhookId: uuid(name) });
}
function uuid(seed) {
  const h = require('crypto').createHash('sha1').update('social-publisher:' + seed).digest('hex');
  return h.slice(0, 8) + '-' + h.slice(8, 12) + '-4' + h.slice(13, 16) + '-a' + h.slice(17, 20) + '-' + h.slice(20, 32);
}

